create table if not exists projetse.organizations (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists projetse.profiles (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users (id) on delete cascade,
  full_name text not null,
  email text not null,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists projetse.organization_members (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references projetse.organizations (id) on delete cascade,
  profile_id bigint not null references projetse.profiles (id) on delete cascade,
  role text not null check (role in ('admin', 'gestora', 'responsavel_tecnica', 'revisora')),
  status text not null default 'active' check (status in ('active', 'invited', 'disabled')),
  created_at timestamptz not null default now(),
  unique (organization_id, profile_id)
);

