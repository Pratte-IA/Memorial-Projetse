create table if not exists projetse.modelos_documento (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references projetse.organizations (id) on delete cascade,
  nome text not null,
  tipo text,
  status text not null default 'ativo',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists projetse.clausulas (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references projetse.organizations (id) on delete cascade,
  modelo_id bigint references projetse.modelos_documento (id) on delete set null,
  titulo text not null,
  categoria text,
  resumo text,
  template text not null,
  variaveis text[],
  status text not null default 'publicada',
  ordem integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists projetse.memoriais (
  id bigint generated by default as identity primary key,
  empreendimento_id bigint not null references projetse.empreendimentos (id) on delete cascade,
  versao integer not null default 1,
  status text not null default 'rascunho' check (
    status in ('rascunho', 'gerado', 'em_revisao', 'aprovado', 'exportado')
  ),
  created_by_profile_id bigint references projetse.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists projetse.memorial_secoes (
  id bigint generated by default as identity primary key,
  memorial_id bigint not null references projetse.memoriais (id) on delete cascade,
  clausula_id bigint references projetse.clausulas (id) on delete set null,
  titulo text not null,
  conteudo text,
  status text not null default 'nao_gerada' check (
    status in ('nao_gerada', 'gerada', 'em_revisao', 'com_pendencia', 'aprovada')
  ),
  ordem integer not null default 0,
  approved_by_profile_id bigint references projetse.profiles (id) on delete set null,
  approved_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists projetse.document_exports (
  id bigint generated by default as identity primary key,
  memorial_id bigint not null references projetse.memoriais (id) on delete cascade,
  empreendimento_id bigint not null references projetse.empreendimentos (id) on delete cascade,
  tipo text not null check (tipo in ('revisao', 'final')),
  formato text not null check (formato in ('docx', 'pdf')),
  storage_path text,
  status text not null default 'pendente',
  created_by_profile_id bigint references projetse.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists projetse.pendencias (
  id bigint generated by default as identity primary key,
  empreendimento_id bigint not null references projetse.empreendimentos (id) on delete cascade,
  entidade_tipo text,
  entidade_id bigint,
  severidade text not null default 'atencao' check (severidade in ('info', 'atencao', 'bloqueante')),
  mensagem text not null,
  status text not null default 'aberta' check (status in ('aberta', 'resolvida', 'ignorada')),
  created_by_profile_id bigint references projetse.profiles (id) on delete set null,
  resolved_by_profile_id bigint references projetse.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create table if not exists projetse.audit_events (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references projetse.organizations (id) on delete cascade,
  empreendimento_id bigint references projetse.empreendimentos (id) on delete set null,
  profile_id bigint references projetse.profiles (id) on delete set null,
  event_type text not null,
  description text not null,
  metadata jsonb,
  created_at timestamptz not null default now()
