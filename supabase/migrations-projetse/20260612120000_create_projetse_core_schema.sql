grant select, insert, update, delete on all tables in schema projetse to authenticated;
grant select on all tables in schema projetse to anon;
grant usage, select on all sequences in schema projetse to authenticated;

alter default privileges in schema projetse
  grant select, insert, update, delete on tables to authenticated;

alter default privileges in schema projetse
  grant select on tables to anon;
