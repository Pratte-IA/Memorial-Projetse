-- Trigger de perfil ao criar usuário auth (nome específico — não sobrescreve outros apps)
drop trigger if exists projetse_on_auth_user_created on auth.users;

create trigger projetse_on_auth_user_created
  after insert on auth.users
  for each row execute function projetse.handle_new_user();

-- ---------------------------------------------------------------------------
-- Grants de tabela (RLS restringe o acesso efetivo)
